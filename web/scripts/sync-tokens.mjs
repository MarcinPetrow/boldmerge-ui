import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(webRoot, '..');
const sourcePath = path.join(repositoryRoot, 'dist/css/tokens.css');
const destinationPath = path.join(webRoot, 'src/styles/tokens.css');
const metadataPath = path.join(webRoot, 'src/generated/token-metadata.ts');
const check = process.argv.includes('--check');

const source = await readFile(sourcePath, 'utf8');
const designPackage = JSON.parse(await readFile(path.join(repositoryRoot, 'package.json'), 'utf8'));
const digest = createHash('sha256').update(source).digest('hex');
const property = (name) => {
  const match = new RegExp(`^\\s*${name}:\\s*([^;]+);`, 'm').exec(source);
  if (!match?.[1]) throw new Error(`Canonical token artifact is missing ${name}`);
  return match[1].trim();
};
const tones = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const strategy = {
  lightness: Object.fromEntries(tones.map((tone) => [tone, Number(property(`--bm-accent-strategy-lightness-${tone}`))])),
  maxChroma: {
    light: Number(property('--bm-accent-strategy-max-chroma-light')),
    mid: Number(property('--bm-accent-strategy-max-chroma-mid')),
    dark: Number(property('--bm-accent-strategy-max-chroma-dark')),
  },
};
const contrastReferences = {
  lightCanvas: property('--bm-color-neutral-50'),
  darkCanvas: property('--bm-color-neutral-950'),
  lightOnSolid: property('--bm-color-neutral-0'),
};
const metadata = `// Generated by scripts/sync-tokens.mjs. Do not edit.\nexport const DESIGN_TOKENS_VERSION = ${JSON.stringify(designPackage.version)};\nexport const DESIGN_TOKENS_SHA256 = ${JSON.stringify(digest)};\nexport const DESIGN_ACCENT_STRATEGY = ${JSON.stringify(strategy, null, 2)} as const;\nexport const DESIGN_CONTRAST_REFERENCES = ${JSON.stringify(contrastReferences, null, 2)} as const;\n`;

if (check) {
  const mismatches = [];
  if ((await readFile(destinationPath, 'utf8').catch(() => '')) !== source) mismatches.push('src/styles/tokens.css');
  if ((await readFile(metadataPath, 'utf8').catch(() => '')) !== metadata) mismatches.push('src/generated/token-metadata.ts');
  if (mismatches.length) throw new Error(`Canonical token snapshot is stale: ${mismatches.join(', ')}. Run npm run tokens:sync.`);
  process.stdout.write(`Canonical token snapshot matches ${designPackage.version} (${digest}).\n`);
} else {
  await writeFile(destinationPath, source, 'utf8');
  await writeFile(metadataPath, metadata, 'utf8');
  process.stdout.write(`Synchronized canonical tokens ${designPackage.version} (${digest}).\n`);
}
